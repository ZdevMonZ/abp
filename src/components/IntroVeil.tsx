import type { CSSProperties } from "react";
import { BACKDROP } from "@/components/sections/HeroSection";

/**
 * 첫 화면 열림(페이드인)
 * ---------------------------------------------------------------------------
 * 사이트를 열면 **화면 전체가** 어둠에서 서서히 밝아집니다.
 *
 * 하는 일은 한 가지뿐입니다 — 첫 화면 배경색과 똑같은 어두운 막 한 장을
 * 사이트 맨 위층에 덮어 두고, 그 막을 서서히 투명하게 만듭니다.
 *
 * ★ 왜 첫 화면(HeroSection.tsx) 안이 아니라 여기에 있나요?
 *   위쪽 메뉴 바(SOLION & LUNION·BRAND…)와 오른쪽 점 네비게이션·아래 버튼들은
 *   첫 화면 **바깥**에 떠 있는 요소입니다. 막을 첫 화면 안에만 씌우면
 *   사진만 어둡고 메뉴 글자만 처음부터 환하게 떠 있어서, "화면이 밝아진다"가
 *   아니라 "사진만 늦게 켜진다"로 보입니다. 그래서 사이트 전체를 덮습니다.
 *
 * 사진·글자는 처음부터 100% 로 그려지고 그 **위에 덮인 막**만 옅어지는 방식이라,
 * 구글이 재는 화면 표시 속도 점수에는 손해가 없습니다.
 * 막은 클릭을 통과시키고(pointer-events-none) 화면 읽어주는 프로그램에도
 * 잡히지 않습니다(aria-hidden). 연출이 끝나면 완전히 투명해집니다.
 */

/** 페이드인을 쓸지 (false = 예전처럼 처음부터 환하게 떠 있음) */
const FX_INTRO = true;

/**
 * 어둠에서 100% 밝기까지 걸리는 시간(ms).
 *   줄이면(700) 산뜻하고, 늘리면(1500) 더 묵직합니다.
 *   ★ 1600 을 넘기면 "사이트가 느리다"로 읽히기 시작합니다.
 *
 *   실제로 밝아지는 모양 (1200 기준) — 브라우저에서 직접 재 본 값입니다
 *     0.1초 6% · 0.2초 16% · 0.3초 29% · 0.5초 57% · 0.7초 80% · 0.9초 93% · 1.2초 100%
 *   처음 한 박자 어둡게 머물다 고르게 차오릅니다. 사람 눈은 어두운 쪽의 변화를
 *   더 크게 느끼기 때문에, 앞부분을 일부러 살짝 눌러 둔 곡선입니다.
 *   (곡선 자체는 globals.css 의 .intro-veil 에 있습니다)
 *
 *   ★ 이 값을 바꾸면 HeroSection.tsx 의 SLOGAN_DELAY_MS · CUE_DELAY_MS 도
 *     같이 옮기세요. 화면이 거의 다 밝아진 뒤 슬로건이 도착해야 순서가 맞습니다.
 */
const INTRO_MS = 1200;

export function IntroVeil() {
  if (!FX_INTRO) return null;

  return (
    <div
      aria-hidden="true"
      className="intro-veil"
      style={
        {
          // 첫 화면 배경색과 같은 색이어야 사진이 그 색에서 떠오르는 것처럼 보입니다
          backgroundColor: BACKDROP,
          "--intro-ms": `${INTRO_MS}ms`,
        } as CSSProperties
      }
    />
  );
}
